-- Needed for editing and deleting entries from the shared tracker
create policy "battleboard update"
on public.workout_logs for update
to anon
using (true)
with check (person in ('julia','jana') and weight >= 0 and sets > 0 and reps > 0);

create policy "battleboard delete"
on public.workout_logs for delete
to anon
using (true);
